-- count(*) whose WHERE the access window enforces is answered from the
-- store's per-subtree counts; every shape must count what a scan would.
CREATE TABLE c (id INTEGER PRIMARY KEY, a INTEGER, b TEXT, r REAL, n);
CREATE INDEX c_a ON c (a);
CREATE INDEX c_ab ON c (a, b);
CREATE INDEX c_b_desc ON c (b DESC);
CREATE INDEX c_bn ON c (b COLLATE NOCASE);
CREATE INDEX c_r ON c (r);
WITH RECURSIVE s(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM s WHERE i < 5000)
INSERT INTO c SELECT i, CASE WHEN i % 13 = 0 THEN NULL ELSE i % 97 END,
       CASE i % 5 WHEN 0 THEN 'x' || (i % 31) WHEN 1 THEN 'X' || (i % 31) WHEN 2 THEN NULL ELSE 'y' || (i % 7) END,
       CASE WHEN i % 17 = 0 THEN NULL ELSE (i % 211) * 0.5 END, i % 3 FROM s;
