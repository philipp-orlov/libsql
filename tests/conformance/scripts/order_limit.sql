-- ORDER BY with LIMIT keeps a bounded top-N; ties, NULLs and offsets must
-- come out as a full sort would put them.
CREATE TABLE o (id INTEGER PRIMARY KEY, k, s TEXT COLLATE NOCASE, r REAL);
WITH RECURSIVE n(i) AS (SELECT 1 UNION ALL SELECT i + 1 FROM n WHERE i < 3000)
INSERT INTO o SELECT i, CASE WHEN i % 11 = 0 THEN NULL ELSE (i * 37) % 50 END,
       CASE i % 4 WHEN 0 THEN 'a' WHEN 1 THEN 'A' WHEN 2 THEN 'b' ELSE NULL END, (i % 7) * 1.5 FROM n;
SELECT id, k FROM o ORDER BY k LIMIT 10;
SELECT id, k FROM o ORDER BY k DESC LIMIT 25 OFFSET 40;
SELECT id, k FROM o ORDER BY k NULLS LAST LIMIT 7;
SELECT id, k FROM o ORDER BY k DESC NULLS FIRST LIMIT 300 OFFSET 2;
SELECT id, s FROM o ORDER BY s LIMIT 12;
SELECT id, s FROM o ORDER BY s COLLATE BINARY DESC, k LIMIT 15 OFFSET 1000;
SELECT id, r, k FROM o ORDER BY r, k DESC LIMIT 1;
SELECT id, r FROM o ORDER BY r DESC LIMIT 2999;
SELECT k, count(*) FROM o GROUP BY k ORDER BY 2 DESC, 1 LIMIT 5;
SELECT id FROM o ORDER BY k % 3, id DESC LIMIT 9 OFFSET 2990;
SELECT id FROM (SELECT * FROM o ORDER BY k LIMIT 100) ORDER BY id LIMIT 5;
SELECT id, k FROM o WHERE k > 40 ORDER BY k, s LIMIT 33;
